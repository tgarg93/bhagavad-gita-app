// Generates src/data/audioClipDurations.ts — an authoritative { sectionId: ms }
// map of every bundled narration clip's true duration, measured with ffprobe.
//
// Why this exists: the pre-recorded read-along highlight advances by
// positionMillis / durationMs (PrerecordedController). On Android, MediaPlayer
// often fails to report a duration for these mp3s, so durationMs stayed 0 and
// the highlight froze on the first sentence. Seeding the duration from this map
// removes the dependency on the platform reporting it.
//
// Re-run after adding/changing clips (a native build anyway):
//   node scripts/generate-audio-durations.mjs
//
// Requires ffprobe on PATH (brew install ffmpeg).

import { execFileSync } from 'node:child_process';
import { readdirSync, writeFileSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const AUDIO_DIRS = ['assets/audio/foundations', 'assets/audio/ramayana'];

function durationMs(file) {
  const out = execFileSync(
    'ffprobe',
    ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file],
    { encoding: 'utf8' }
  ).trim();
  const secs = parseFloat(out);
  if (!Number.isFinite(secs)) throw new Error(`ffprobe gave no duration for ${file}`);
  return Math.round(secs * 1000);
}

const durations = {};
let count = 0;
for (const dir of AUDIO_DIRS) {
  const abs = join(root, dir);
  let files;
  try {
    files = readdirSync(abs).filter((f) => f.endsWith('.mp3'));
  } catch {
    console.warn(`(skipping missing dir ${dir})`);
    continue;
  }
  for (const f of files.sort()) {
    const sectionId = basename(f, '.mp3'); // filename stem == manifest sectionId
    durations[sectionId] = durationMs(join(abs, f));
    count++;
  }
}

const entries = Object.keys(durations)
  .sort()
  .map((k) => `  '${k}': ${durations[k]},`)
  .join('\n');

const banner = `// AUTO-GENERATED by scripts/generate-audio-durations.mjs — do not edit by hand.
// Authoritative narration-clip durations in milliseconds, keyed by section id
// (the mp3 filename stem, which is also the audio-manifest key). Seeds
// PrerecordedController.durationMs so the read-along highlight never depends on
// the platform (Android MediaPlayer) reporting a clip duration. Regenerate with
//   node scripts/generate-audio-durations.mjs
`;

const body = `${banner}
export const audioClipDurationMs: Record<string, number> = {
${entries}
};
`;

const outPath = join(root, 'src/data/audioClipDurations.ts');
writeFileSync(outPath, body);
console.log(`Wrote ${count} clip durations → src/data/audioClipDurations.ts`);
